/**
 * operator-gui-scale.js — Firefox kiosk UI scaling for the operator_gui destination.
 *
 * Reported live 2026-07-21: switching the operator monitor's cable to a true DisplayPort link
 * unblocked 2160p50 (the prior HDMI-adapter link couldn't negotiate it), and immediately surfaced
 * a second bug — the kiosk's UI (buttons/text/panels) render tiny at 4K. The app's CSS is
 * px-heavy and was always designed against ~1920x1080 CSS pixels (client/styles/*.css: ~2213 `px`
 * uses vs ~456 `rem`, 42 `vw`/`vh`); it only ever looked right at 1080p by coincidence, since the
 * kiosk's browser window is bound 1:1 to the destination's pixel resolution with no DPI/zoom
 * layer (operator-gui-launcher.js spawns plain `firefox-esr --kiosk`, no `--force-device-scale-factor`
 * or profile pref existed before this file).
 *
 * Fix: force Firefox's `layout.css.devPixelsPerPx` pref (the standard Linux-kiosk DPI-scale
 * override) to the destination's resolution ratio over that same 1920x1080 baseline, via the
 * profile's `user.js` (read fresh on every Firefox start, and takes precedence over `prefs.js`).
 */
'use strict'

const fs = require('fs')
const path = require('path')

const BASELINE_WIDTH = 1920
const BASELINE_HEIGHT = 1080
const MIN_RATIO = 1
const MAX_RATIO = 4

/**
 * @param {{width?: number, height?: number}|null|undefined} dims operator_gui channel raster dims
 * @returns {number} `layout.css.devPixelsPerPx` value — 1 at/under the 1920x1080 CSS baseline,
 *   scaling up linearly above it (e.g. 2 at 3840x2160), clamped to [1, 4] and rounded to 2dp.
 */
function computeOperatorGuiDevicePixelRatio(dims) {
	const w = Number(dims?.width)
	const h = Number(dims?.height)
	if (!(w > 0) || !(h > 0)) return MIN_RATIO
	const ratio = Math.min(w / BASELINE_WIDTH, h / BASELINE_HEIGHT)
	if (!Number.isFinite(ratio)) return MIN_RATIO
	return Math.min(MAX_RATIO, Math.max(MIN_RATIO, Math.round(ratio * 100) / 100))
}

/**
 * @param {number} ratio
 * @returns {string} Firefox profile `user.js` content
 */
function buildOperatorGuiUserJs(ratio) {
	return (
		'// Generated by operator-gui-launcher.js — scales the kiosk UI so it reads at a\n' +
		"// consistent physical size regardless of the operator_gui destination's resolution.\n" +
		`user_pref("layout.css.devPixelsPerPx", "${ratio}");\n`
	)
}

/**
 * Writes the scale pref into the Firefox profile's `user.js`. Best-effort: logs and returns null
 * on failure rather than blocking the kiosk launch.
 * @param {string} profileDir
 * @param {{width?: number, height?: number}|null|undefined} dims
 * @param {Function} [log]
 * @returns {number|null} the ratio written, or null on failure
 */
function writeOperatorGuiScalePref(profileDir, dims, log) {
	const ratio = computeOperatorGuiDevicePixelRatio(dims)
	try {
		fs.writeFileSync(path.join(profileDir, 'user.js'), buildOperatorGuiUserJs(ratio))
		return ratio
	} catch (e) {
		log?.('warn', `[Operator GUI] launch: scale pref write failed: ${e?.message || e}`)
		return null
	}
}

module.exports = {
	BASELINE_WIDTH,
	BASELINE_HEIGHT,
	MIN_RATIO,
	MAX_RATIO,
	computeOperatorGuiDevicePixelRatio,
	buildOperatorGuiUserJs,
	writeOperatorGuiScalePref,
}
