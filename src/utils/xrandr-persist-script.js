'use strict'

/**
 * Build apply-layout.sh content with custom xrandr modes before layout apply (WO-80).
 */

/** @param {string} token */
function assertSafeXrandrToken(token, label) {
	const s = String(token || '').trim()
	if (!s || !/^[A-Za-z0-9._+-]+$/.test(s)) {
		throw new Error(`Unsafe xrandr ${label}: ${JSON.stringify(token)}`)
	}
	return s
}

/**
 * @typedef {{ modeName: string, timings: string[], outputs: string[], width?: number, height?: number, refreshHz?: number, timingKind?: string }} CustomXrandrModePlan
 */

class CustomXrandrModeRegistry {
	constructor() {
		/** @type {Map<string, CustomXrandrModePlan>} */
		this._byName = new Map()
	}

	/**
	 * @param {string} output
	 * @param {{ modeName: string, timings: string[], width?: number, height?: number, refreshHz?: number, timingKind?: string }} plan
	 */
	register(output, plan) {
		const out = assertSafeXrandrToken(output, 'output')
		const modeName = assertSafeXrandrToken(plan.modeName, 'modeName')
		if (!Array.isArray(plan.timings) || plan.timings.length < 9) return
		for (const t of plan.timings) assertSafeXrandrToken(t, 'timing')
		let row = this._byName.get(modeName)
		if (!row) {
			row = {
				modeName,
				timings: [...plan.timings],
				outputs: [],
				width: plan.width,
				height: plan.height,
				refreshHz: plan.refreshHz,
				timingKind: plan.timingKind,
			}
			this._byName.set(modeName, row)
		}
		if (!row.outputs.includes(out)) row.outputs.push(out)
	}

	/** @returns {CustomXrandrModePlan[]} */
	toArray() {
		return [...this._byName.values()].sort((a, b) => a.modeName.localeCompare(b.modeName))
	}
}

/**
 * Idempotent shell lines: one --newmode per unique name, --addmode per output.
 * @param {CustomXrandrModePlan[]} customModes
 * @returns {string[]}
 */
function buildCustomModeBootstrapShellLines(customModes) {
	if (!Array.isArray(customModes) || customModes.length === 0) return []
	const lines = ['# Custom xrandr modes (recreate before layout — WO-80)']
	for (const m of customModes) {
		const modeName = assertSafeXrandrToken(m.modeName, 'modeName')
		const timingArgs = m.timings.map((t) => assertSafeXrandrToken(t, 'timing')).join(' ')
		lines.push(`xrandr --display :0 --newmode ${modeName} ${timingArgs} 2>/dev/null || true`)
		for (const out of m.outputs) {
			const output = assertSafeXrandrToken(out, 'output')
			lines.push(`xrandr --display :0 --addmode ${output} ${modeName} 2>/dev/null || true`)
		}
	}
	return lines
}

/**
 * @param {{
 *   xauth: string,
 *   xrandrLayoutCmd: string,
 *   customModes?: CustomXrandrModePlan[],
 *   sessionLines?: string[],
 * }} opts
 * @returns {string}
 */
function buildApplyLayoutScriptContent(opts) {
	const xauth = String(opts.xauth || '').trim()
	const layoutCmd = String(opts.xrandrLayoutCmd || '').trim()
	const sessionLines = Array.isArray(opts.sessionLines) ? opts.sessionLines : []
	const customLines = buildCustomModeBootstrapShellLines(opts.customModes || [])
	const body = [...customLines, layoutCmd, ...sessionLines].filter(Boolean).join('\n')
	return `#!/bin/bash
# Generated by HighAsCG
export DISPLAY=:0
export XAUTHORITY=${xauth}
${body}
`
}

/**
 * @param {CustomXrandrModePlan[]} customModes
 * @returns {object}
 */
function customModesToApplyMeta(customModes) {
	return {
		generatedAt: new Date().toISOString(),
		modes: (customModes || []).map((m) => ({
			modeName: m.modeName,
			width: m.width,
			height: m.height,
			refreshHz: m.refreshHz,
			timingKind: m.timingKind,
			outputs: [...(m.outputs || [])],
		})),
	}
}

module.exports = {
	CustomXrandrModeRegistry,
	buildCustomModeBootstrapShellLines,
	buildApplyLayoutScriptContent,
	customModesToApplyMeta,
	assertSafeXrandrToken,
}
