'use strict'

const fs = require('node:fs')
const path = require('node:path')

/**
 * WO-407: which display's vblank caspar's GL swaps gate on (__GL_SYNC_DISPLAY_DEVICE).
 *
 * On a multi-head X screen the driver defaults to ONE head (the primary — the operator
 * monitor), and the PGM display beats against it: irregular micro-stutter on air while the
 * operator GUI stays smooth. See docs/reference/multi-head-gl-vblank-sync.md.
 *
 * AUTO (default): screen 1's connector from the same layout plan that positions the
 * outputs (`calculateLayoutPositions().screens[1].sysId` — the `--output DP-0 --pos 0x0`
 * source of truth). Override via casparServer.caspar_gl_sync_display:
 * '' | 'auto' = auto, 'off' = never set, anything else = connector name verbatim.
 */

const ENV_FILE_DIR = path.join(process.env.HOME || '/home/casparcg', '.config', 'highascg')
const ENV_FILE = path.join(ENV_FILE_DIR, 'caspar-env')

/**
 * @param {Record<string, any>} config app config
 * @returns {string | null} connector name, or null for "do not set"
 */
function resolveGlSyncDisplay(config) {
	const cs = config?.casparServer && typeof config.casparServer === 'object' ? config.casparServer : {}
	const raw = String(cs.caspar_gl_sync_display || '').trim()
	const lower = raw.toLowerCase()
	if (lower === 'off' || lower === 'none') return null
	if (raw && lower !== 'auto') return raw
	try {
		const { calculateLayoutPositions } = require('./os-layout-calculator')
		const plan = calculateLayoutPositions(config)
		const s1 = plan?.screens?.[1] ?? plan?.screens?.['1']
		const sysId = String(s1?.sysId || '').trim()
		if (sysId) return sysId
	} catch {
		/* layout plan unavailable (headless/test) — fall through */
	}
	const sid = String(cs.screen_1_system_id || '').trim()
	return sid || null
}

/**
 * Rewrite the machine-owned caspar-env file run.sh sources at every caspar launch.
 * Called on every config Apply so the value tracks layout changes; a null resolution
 * writes the file WITHOUT the var so a stale connector can never linger.
 * @param {{ config: Record<string, any>, log?: Function }} ctx
 * @returns {{ display: string | null, file: string }}
 */
function writeCasparGlSyncEnvFile(ctx) {
	const display = resolveGlSyncDisplay(ctx?.config || {})
	const lines = [
		'# AUTO-GENERATED by HighAsCG (WO-407) — do not hand-edit; rewritten on every config Apply.',
		'# GL swaps gate on the PGM display’s vblank: docs/reference/multi-head-gl-vblank-sync.md',
		'# Override: casparServer.caspar_gl_sync_display = auto | off | <connector>',
	]
	if (display) lines.push(`CASPAR_GL_SYNC_DISPLAY=${display}`)
	fs.mkdirSync(ENV_FILE_DIR, { recursive: true })
	fs.writeFileSync(ENV_FILE, lines.join('\n') + '\n')
	ctx?.log?.('info', `[Caspar GL sync] caspar-env written: ${display ? `sync display ${display}` : 'no sync display (off/unresolved)'}`)
	return { display, file: ENV_FILE }
}

module.exports = { resolveGlSyncDisplay, writeCasparGlSyncEnvFile, ENV_FILE }
