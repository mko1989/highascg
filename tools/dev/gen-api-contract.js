#!/usr/bin/env node
'use strict'

/**
 * WO-598 A — generate the client contract tables from src/:
 *   docs/wiki/api/contract/http.md   every HTTP route: registry registrations (`routes.get/post/delete('/api/…')`)
 *                                    and the paths fallthrough handlers match by literal (`p === '/api/…'`)
 *   docs/wiki/api/contract/ws.md     every WebSocket message type, by direction
 * `--check` regenerates in memory and exits 1 when the committed files differ (smoke-wo598-api-contract runs it).
 * No line numbers on purpose: unrelated edits must not make the docs stale.
 */

const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '../..')
const OUT = path.join(ROOT, 'docs/wiki/api/contract')
const IN_FILES = ['src/server/', 'src/tracking/register.js', 'src/tracking/fixtures-watch.js'] // WO-797: the previs watch
const { WS: COMPANION_WS } = require('../../src/companion-bridge/contract')
const { TYPE_TO_PATH } = require('../../src/server/ws-amcp-dispatch')

function walk(dir, out = []) {
	for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
		const p = path.join(dir, e.name)
		if (e.isDirectory()) walk(p, out)
		else if (e.name.endsWith('.js')) out.push(p)
	}
	return out
}

/** First sentence of the file's first block comment (the module's own description). */
function moduleBlurb(src) {
	const m = /\/\*\*?([\s\S]*?)\*\//.exec(src)
	if (!m) return ''
	const text = m[1]
		.split('\n')
		.map((l) => l.replace(/^\s*\*\s?/, '').trim())
		.filter((l) => l && !l.startsWith('@'))
		.join(' ')
	const first = text.split(/(?<=\.)\s/)[0] || ''
	return first.replace(/\|/g, '\\|').slice(0, 160)
}

/** Method of the handler a literal sits in: nearest preceding `function handleGet|Post|Put|Delete`. */
function enclosingMethod(src, idx) {
	const re = /function\s+handle(Get|Post|Put|Delete)\b/g
	let m
	let last = null
	while ((m = re.exec(src)) && m.index < idx) last = m[1].toUpperCase()
	return last || '*'
}

function scan() {
	const files = [...walk(path.join(ROOT, 'src')), path.join(ROOT, 'index.js')].sort() // index.js: boot-time broadcasts (log_line, timeline.playback)
	const http = new Map()
	const ws = new Map()
	const blurbs = new Map()
	const add = (map, key, row) => {
		if (!map.has(key)) map.set(key, row)
		else if (!map.get(key).files.includes(row.files[0])) map.get(key).files.push(row.files[0])
	}
	for (const f of files) {
		const src = fs.readFileSync(f, 'utf8')
		const rel = path.relative(ROOT, f)
		let hit = false
		for (const m of src.matchAll(/routes\.(get|post|delete)\(\s*'(\/api\/[^']+)'/g)) {
			add(http, `${m[2]} ${m[1].toUpperCase()}`, { path: m[2], method: m[1].toUpperCase(), how: 'registry', files: [rel] })
			hit = true
		}
		for (const m of src.matchAll(/\b(?:p|path|pathname|reqPath|urlPath)\s*===\s*'(\/api\/[^']+)'/g)) {
			const method = enclosingMethod(src, m.index)
			add(http, `${m[1]} ${method}`, { path: m[1], method, how: 'handler', files: [rel] })
			hit = true
		}
		const consts = Object.fromEntries([...src.matchAll(/\bconst ([A-Z_]+)\s*=\s*'([^']+)'/g)].map((m) => [m[1], m[2]]))
		const out = (t) => {
			add(ws, `out ${t}`, { type: t, dir: 'server → clients', files: [rel] })
			hit = true
		}
		for (const m of src.matchAll(/(?:_wsBroadcast|\bbroadcast)\(\s*(?:'([^']+)'|([A-Z_]+)\b)/g)) {
			const t = m[1] || consts[m[2]]
			if (t) out(t)
		}
		for (const m of src.matchAll(/(?:JSON\.stringify|safeStringify)\(\{\s*type:\s*'([^']+)'/g)) out(m[1])
		if (rel.startsWith('src/server/')) for (const m of src.matchAll(/^\s*type:\s*'([^']+)',$/gm)) out(m[1])
		/* Inbound: only the operator WebSocket handlers (child-process IPC also switches on msg.type). */
		if (IN_FILES.some((f) => rel.startsWith(f))) {
			for (const m of src.matchAll(/(?<!typeof )\b(?:msg\.type|t)\s*[!=]==\s*(?:'([^']+)'|COMPANION_WS\.([A-Z_]+))/g)) {
				const t = m[1] || COMPANION_WS[m[2]] || `COMPANION_WS.${m[2]}`
				add(ws, `in ${t}`, { type: t, dir: 'client → server', files: [rel] })
				hit = true
			}
		}
		if (hit) blurbs.set(rel, moduleBlurb(src))
	}
	/* Structured AMCP messages: { type: 'play' | 'mixer' | …, … } map onto the HTTP route of the same name. */
	for (const [t, route] of Object.entries(TYPE_TO_PATH)) {
		add(ws, `in ${t}`, { type: t, dir: 'client → server', files: ['src/server/ws-amcp-dispatch.js'], note: `→ ${route}` })
	}
	return { http, ws, blurbs }
}

const HEADER = (what) =>
	`<!-- Generated by \`node tools/dev/gen-api-contract.js\` — do not edit. CI (smoke-wo598-api-contract) fails when it is stale. -->\n\n# ${what}\n\n`

function render() {
	const { http, ws, blurbs } = scan()
	const rows = [...http.values()].sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))
	const usedHttp = new Set(rows.flatMap((r) => r.files))
	let h = HEADER('HTTP contract')
	h +=
		'Every `/api/…` route the node answers. **registry** = registered on the RouteRegistry (`src/api/router.js` and the\n'
	h +=
		"modules' `register(routes)`; `*` = wildcard, the module matches the rest). **handler** = matched by literal inside a\n"
	h +=
		"module's handler (fallthrough chain in `src/api/router-dispatch.js`); method `*` = any. Bodies and replies: the\n"
	h += "module's JSDoc and the topic pages in `docs/wiki/api/`.\n\n"
	h += `${rows.length} routes.\n\n| Method | Path | How | Module |\n|---|---|---|---|\n`
	for (const r of rows)
		h += `| ${r.method} | \`${r.path}\` | ${r.how} | ${r.files.map((f) => `\`${f}\``).join(', ')} |\n`
	h += '\n## Modules\n\n| Module | What it is |\n|---|---|\n'
	for (const f of [...usedHttp].sort()) h += `| \`${f}\` | ${blurbs.get(f) || ''} |\n`

	const wrows = [...ws.values()].sort((a, b) => a.dir.localeCompare(b.dir) || a.type.localeCompare(b.type))
	let w = HEADER('WebSocket contract')
	w +=
		"Message types on the node's WebSocket (`/` on the HTTP port; envelope `{ type, data }`). **server → clients** =\n"
	w +=
		'broadcasts and direct sends; **client → server** = types the node acts on. Payloads: the sending / handling module.\n\n'
	w += `${wrows.length} types.\n\n| Direction | Type | Module | Note |\n|---|---|---|---|\n`
	for (const r of wrows)
		w += `| ${r.dir} | \`${r.type}\` | ${r.files.map((f) => `\`${f}\``).join(', ')} | ${r.note ? `\`${r.note}\`` : ''} |\n`
	return { 'http.md': h, 'ws.md': w, rows }
}

if (require.main === module) {
	const out = render()
	const check = process.argv.includes('--check')
	let stale = []
	for (const name of ['http.md', 'ws.md']) {
		const file = path.join(OUT, name)
		const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
		if (check) {
			if (cur !== out[name]) stale.push(name)
		} else {
			fs.mkdirSync(OUT, { recursive: true })
			fs.writeFileSync(file, out[name])
		}
	}
	if (check && stale.length) {
		console.error(`[api-contract] stale: ${stale.join(', ')} — run: node tools/dev/gen-api-contract.js`)
		process.exit(1)
	}
	if (!check) console.log(`[api-contract] wrote ${out.rows.length} routes`)
}

module.exports = { render, scan }
