'use strict'

/**
 * WO-870 Phase 2: the managed penguins-eggs 26.10 config (custom.exclude.list + custom.yaml) is generated from
 * the repo, deterministically, and obeys the coa parser's rules (offline, no root, no eggs/coa).
 */

const { describe, it } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { execFileSync, spawnSync } = require('child_process')

const LIVE_USB = path.resolve(__dirname, '../eggs/live-usb')
const GEN = path.join(LIVE_USB, 'generate-eggs-config.js')
const gen = require(GEN)

const patterns = (text) => text.split('\n').filter((l) => l.trim() && !l.startsWith('#'))
const list = gen.buildExcludeList({ embedServer: true })
const pats = patterns(list)

describe('WO-870 generate-eggs-config: custom.exclude.list', () => {
	it('is deterministic (two builds and the CLI agree byte for byte)', () => {
		assert.equal(gen.buildExcludeList({ embedServer: true }), list)
		assert.equal(execFileSync('node', [GEN, 'exclude', '--embed', '1'], { encoding: 'utf8' }), list)
	})

	it('starts with a generated / do-not-edit header naming its sources', () => {
		const head = list.split('\n').slice(0, 6).join('\n')
		assert.match(head, /GENERATED by tools\/eggs\/live-usb\/generate-eggs-config\.js/)
		assert.match(head, /DO NOT EDIT/)
		assert.match(head, /penguins-eggs-exclude-decklink\.list/)
	})

	it('contains the media line (the space check subtracts it), home/eggs, and the DeckLink + stock entries', () => {
		for (const l of ['home/casparcg/highascg/media/*', 'home/eggs', 'usr/lib/blackmagic', 'var/lib/docker/', 'snap/']) {
			assert.ok(pats.includes(l), `missing ${l}`)
		}
	})

	it('has no inline comments, no leading slash, no blanks-as-patterns, no duplicates', () => {
		for (const l of pats) {
			assert.ok(!l.includes('#'), `inline comment in: ${l}`)
			assert.ok(!l.startsWith('/'), `leading slash: ${l}`)
			assert.equal(l, l.trim(), `untrimmed: "${l}"`)
		}
		assert.equal(new Set(pats).size, pats.length, 'duplicate pattern')
	})

	it('every lib/ lib64/ bin/ sbin/ line has its usr/ twin (merged-usr, WO-430)', () => {
		const lib = pats.filter((l) => gen.MERGED_USR_RE.test(l))
		assert.ok(lib.length >= 3, 'expected lib-ish lines (DeckLink udev rules / dkms modules / lib/live)')
		for (const l of lib) assert.ok(pats.includes(`usr/${l}`), `no usr/ twin for ${l}`)
		assert.ok(pats.includes('usr/lib/modules/*/updates/dkms/blackmagic.ko*'))
	})

	it('embed-server default keeps node_modules; --embed 0 (WO-47) excludes it, and both keep the media line', () => {
		assert.ok(!pats.includes('home/casparcg/highascg/node_modules'))
		const wo47 = patterns(gen.buildExcludeList({ embedServer: false }))
		assert.ok(wo47.includes('home/casparcg/highascg/node_modules'))
		assert.ok(wo47.includes('home/casparcg/highascg/media/*'))
	})

	it('every vendored fragment line survives (nothing silently dropped)', () => {
		for (const f of fs.readdirSync(LIVE_USB).filter((n) => /^penguins-eggs-exclude-(stock-custom|old-template|decklink|highascg-embed-server)\.list$/.test(n))) {
			for (const raw of fs.readFileSync(path.join(LIVE_USB, f), 'utf8').split('\n')) {
				const l = gen.cleanLine(raw)
				if (l) assert.ok(pats.includes(l), `${f}: ${l} missing from output`)
			}
		}
	})
})

describe('WO-870 generate-eggs-config: custom.yaml', () => {
	const yaml = gen.buildCustomYaml({ branch: '615' })
	it('carries anonymous, remaster.iso_prefix and xz', () => {
		assert.match(yaml, /^anonymous: true$/m)
		assert.match(yaml, /^remaster:$/m)
		assert.match(yaml, /^ {2}iso_prefix: highascg-nvidia-615$/m)
		assert.match(yaml, /^ {4}algorithm: "xz"$/m)
	})
	it('does not enable the calamares installer (only a comment)', () => {
		assert.ok(!/^\s*installer:/m.test(yaml))
	})
	it('rejects a non-numeric branch', () => {
		assert.throws(() => gen.buildCustomYaml({ branch: 'abc' }))
		assert.throws(() => gen.buildCustomYaml({}))
	})
})

describe('WO-870 install-eggs-config.sh / verify-eggs-config.sh', () => {
	const env = { ...process.env, HIGHASCG_NVIDIA_DRIVER: '615', HIGHASCG_ISO_EMBED_SERVER: '1' }
	const sh = (script, args, extra = {}) =>
		spawnSync('bash', [path.join(LIVE_USB, script), ...args], { encoding: 'utf8', env: { ...env, ...extra } })

	it('--out writes both files identical to the generator, no root needed', () => {
		const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wo870-cfg-'))
		try {
			const r = sh('install-eggs-config.sh', ['--out', dir])
			assert.equal(r.status, 0, r.stderr)
			assert.equal(fs.readFileSync(path.join(dir, 'custom.exclude.list'), 'utf8'), list)
			assert.equal(fs.readFileSync(path.join(dir, 'custom.yaml'), 'utf8'), gen.buildCustomYaml({ branch: '615' }))
		} finally {
			fs.rmSync(dir, { recursive: true, force: true })
		}
	})

	it('--apply into a scratch EGGS_CONF_DIR is idempotent, backs up a differing file, and verify passes then fails', () => {
		const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wo870-conf-'))
		try {
			const conf = { EGGS_CONF_DIR: dir }
			fs.writeFileSync(path.join(dir, 'custom.yaml'), 'old: 1\n')
			assert.equal(sh('install-eggs-config.sh', ['--apply'], conf).status, 0)
			assert.ok(fs.readdirSync(dir).some((n) => n.startsWith('custom.yaml.bak-')), 'previous yaml not backed up')
			const second = sh('install-eggs-config.sh', ['--apply'], conf)
			assert.match(second.stdout, /unchanged: .*custom\.exclude\.list/)
			assert.equal(fs.readdirSync(dir).filter((n) => n.includes('.bak-')).length, 1, 'idempotent run made a backup')
			assert.equal(sh('verify-eggs-config.sh', [], conf).status, 0)
			fs.appendFileSync(path.join(dir, 'custom.exclude.list'), 'x\n')
			const bad = sh('verify-eggs-config.sh', [], conf)
			assert.equal(bad.status, 1)
			assert.match(bad.stdout, /FAIL custom\.exclude\.list/)
			assert.match(bad.stdout, /PASS custom\.yaml/)
		} finally {
			fs.rmSync(dir, { recursive: true, force: true })
		}
	})

	it('scripts parse (bash -n)', () => {
		for (const s of ['install-eggs-config.sh', 'verify-eggs-config.sh']) {
			const r = spawnSync('bash', ['-n', path.join(LIVE_USB, s)], { encoding: 'utf8' })
			assert.equal(r.status, 0, r.stderr)
		}
	})
})
