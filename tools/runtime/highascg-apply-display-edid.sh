#!/usr/bin/env bash
# WO-1129 — install / remove an NVIDIA CustomEDID for ONE connector (a forced display mode the panel's EDID lacks).
# Installed to /usr/local/lib/highascg/ by scripts/setup/12-passwordless-sudo.sh (which also grants it NOPASSWD);
# called by src/utils/nvidia-forced-mode-sync.js on a Full Apply, which then restarts X once (nodm).
#
#   highascg-apply-display-edid.sh --install <connector>  < edid.bin    # EDID bytes on stdin
#   highascg-apply-display-edid.sh --remove  <connector>
#
# The EDID comes on stdin, not as a path: root never opens a file in a user-writable directory (no symlink/TOCTOU
# games). It is validated strictly (128·n bytes, header 00ffffffffffff00, every block sums to 0 mod 256, byte 126 =
# n−1) and installed as /etc/X11/highascg-edid/<connector>.bin 0644. Then ONE snippet,
# /etc/X11/xorg.conf.d/98-highascg-custom-edid.conf, is rewritten for all installed files (removed when none remain).
# Nothing else is ever written or deleted.
#
# Why the snippet carries its own Device section WITH the composition options: 09-openbox-autostart.sh ships
# 99-highascg-force-composition.conf (Device "NVIDIA Default Device", ForceCompositionPipeline On). With no Screen
# section, Xorg's implied layout uses only the FIRST Device section it parses ("Using the first device section
# listed"); xorg.conf.d files are read in name order, and options of two Device sections are never merged. A second
# section in 99-… would be ignored, and one in 98-… alone would silently drop ForceCompositionPipeline. So the 98-…
# section is the one X uses, and it copies every Option line of the 99-… section (read-only — that file stays
# 09-openbox-autostart.sh's) next to the CustomEDID line. When the 98-… file goes, X falls back to the 99-… section.
# A full /etc/X11/xorg.conf with its own Device section would win over both; the helper warns about it.
#
# Tests (no root): HIGHASCG_EDID_TEST_ROOT=<dir> prefixes every path. Ignored when running as root.
set -euo pipefail

ROOT=""
if [[ "$(id -u)" -ne 0 ]]; then
	if [[ -n "${HIGHASCG_EDID_TEST_ROOT:-}" && -d "${HIGHASCG_EDID_TEST_ROOT}" ]]; then
		ROOT="${HIGHASCG_EDID_TEST_ROOT}"
	else
		echo "root required" >&2
		exit 1
	fi
fi
EDID_DIR="${ROOT}/etc/X11/highascg-edid"
CONF_DIR="${ROOT}/etc/X11/xorg.conf.d"
SNIPPET="${CONF_DIR}/98-highascg-custom-edid.conf"
COMPOSITION="${CONF_DIR}/99-highascg-force-composition.conf"
XORG_CONF="${ROOT}/etc/X11/xorg.conf"
MAX_BLOCKS=8

die() {
	echo "highascg-apply-display-edid: $*" >&2
	exit 2
}

usage() { die "usage: $0 --install <connector> < edid.bin | --remove <connector>"; }

[[ $# -eq 2 ]] || usage
ACTION="$1"
CONN="$2"
[[ "$CONN" =~ ^[A-Za-z0-9-]+$ ]] || die "bad connector name: ${CONN}"
[[ ${#CONN} -le 32 ]] || die "connector name too long"

validate_edid() {
	local f="$1" size blocks ext
	size="$(stat -c %s "$f")"
	((size >= 128 && size % 128 == 0 && size <= 128 * MAX_BLOCKS)) || die "EDID must be 128·n bytes (got ${size})"
	[[ "$(od -An -v -tx1 -N8 "$f" | tr -d ' \n')" == "00ffffffffffff00" ]] || die "bad EDID header"
	od -An -v -tu1 -w128 "$f" | awk '{ s = 0; for (i = 1; i <= NF; i++) s += $i; if (NF != 128 || s % 256 != 0) bad = 1 } END { exit bad }' ||
		die "EDID block checksum is wrong"
	blocks=$((size / 128))
	ext="$(od -An -v -tu1 -j126 -N1 "$f" | tr -d ' \n')"
	[[ "$ext" == "$((blocks - 1))" ]] || die "EDID byte 126 says ${ext} extensions, file has $((blocks - 1))"
}

write_snippet() {
	local entries=() f c tmp
	shopt -s nullglob
	for f in "${EDID_DIR}"/*.bin; do
		c="$(basename "$f" .bin)"
		[[ "$c" =~ ^[A-Za-z0-9-]+$ ]] && entries+=("${c}:${f}")
	done
	shopt -u nullglob
	if [[ ${#entries[@]} -eq 0 ]]; then
		rm -f "$SNIPPET"
		return
	fi
	mkdir -p "$CONF_DIR"
	tmp="$(mktemp "${CONF_DIR}/.98-highascg-custom-edid.XXXXXX")"
	{
		echo "# Generated by highascg-apply-display-edid.sh (WO-1129) — forced display modes via NVIDIA CustomEDID."
		echo "# Do not edit: rewritten on every forced-mode change, removed when none remain. Carries the Option lines of"
		echo "# 99-highascg-force-composition.conf because X uses only the first Device section (see the helper)."
		echo 'Section "Device"'
		echo '    Identifier "HighAsCG NVIDIA Device"'
		echo '    Driver "nvidia"'
		if [[ -f "$COMPOSITION" ]]; then
			grep -E '^[[:space:]]*Option[[:space:]]+"[A-Za-z0-9]+"[[:space:]]+"[^"]*"[[:space:]]*$' "$COMPOSITION" |
				grep -v '"CustomEDID"' | sed -E 's/^[[:space:]]*/    /' || true
		fi
		local IFS=';'
		printf '    Option "CustomEDID" "%s"\n' "$(echo "${entries[*]}" | sed 's/;/; /g')"
		echo 'EndSection'
	} >"$tmp"
	chmod 0644 "$tmp"
	mv -f "$tmp" "$SNIPPET"
	if [[ -f "$XORG_CONF" ]] && grep -qE '^[[:space:]]*Section[[:space:]]+"Device"' "$XORG_CONF"; then
		echo "highascg-apply-display-edid: WARNING ${XORG_CONF} has its own Device section — CustomEDID may be ignored" >&2
	fi
}

mkdir -p "$EDID_DIR"
chmod 0755 "$EDID_DIR"
exec 9>"${EDID_DIR}/.lock"
flock 9

case "$ACTION" in
--install)
	TMP="$(mktemp "${EDID_DIR}/.incoming.XXXXXX")"
	trap 'rm -f "$TMP"' EXIT
	head -c $((128 * MAX_BLOCKS + 1)) >"$TMP"
	validate_edid "$TMP"
	chmod 0644 "$TMP"
	mv -f "$TMP" "${EDID_DIR}/${CONN}.bin"
	write_snippet
	echo "installed ${EDID_DIR}/${CONN}.bin"
	;;
--remove)
	rm -f "${EDID_DIR}/${CONN}.bin"
	write_snippet
	echo "removed ${CONN}"
	;;
*) usage ;;
esac
