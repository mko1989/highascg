#!/usr/bin/env node
'use strict'

/**
 * WO-870 Phase 2: generate the managed penguins-eggs 26.10 config (offline, deterministic, no root).
 *
 *   node generate-eggs-config.js exclude [--embed 0|1]   -> custom.exclude.list on stdout
 *   node generate-eggs-config.js yaml --branch NNN       -> custom.yaml on stdout
 *
 * The new engine (coa) hands custom.exclude.list to `mksquashfs -wildcards -ef`: only whole-line `#`
 * comments are skipped, paths are liveroot-relative (no leading `/`), and `/lib /bin /sbin /lib64` are
 * symlinks into usr/ there, so every anchored `lib/...` line needs a `usr/lib/...` twin (WO-430).
 * Sources are vendored fragments next to this file — never /etc at build time — so the output is a pure
 * function of the repo (+ the NVIDIA branch for the yaml).
 */

const fs = require('fs')
const path = require('path')

const HERE = __dirname

const SOURCES = {
	stock: 'penguins-eggs-exclude-stock-custom.list',
	oldTemplate: 'penguins-eggs-exclude-old-template.list',
	embedServer: 'penguins-eggs-exclude-highascg-embed-server.list',
	wo47: 'penguins-eggs-exclude-highascg-fragment.list',
	decklink: 'penguins-eggs-exclude-decklink.list',
}

/** Paths that are symlinks into usr/ in the liveroot (merged-usr). */
const MERGED_USR_RE = /^(lib|lib32|lib64|libx32|bin|sbin)(\/|$)/

/** Lines the parser must see: no inline comment, trimmed, no leading `/`, not empty. */
function cleanLine(raw) {
	let line = raw
	const hash = line.indexOf('#')
	if (hash >= 0) line = line.slice(0, hash)
	line = line.trim().replace(/^\/+/, '')
	return line
}

function readFragment(name) {
	const text = fs.readFileSync(path.join(HERE, name), 'utf8')
	return text.split(/\r?\n/).map(cleanLine).filter(Boolean)
}

/** Dedupe in stable order; after every merged-usr line add its usr/ twin. */
function withTwinsAndDedupe(lines) {
	const seen = new Set()
	const out = []
	const push = (l) => {
		if (seen.has(l)) return
		seen.add(l)
		out.push(l)
	}
	for (const l of lines) {
		push(l)
		if (MERGED_USR_RE.test(l)) push(`usr/${l}`)
	}
	return out
}

function buildExcludeList({ embedServer = true } = {}) {
	const server = embedServer ? SOURCES.embedServer : SOURCES.wo47
	const parts = [
		['stock penguins-eggs custom.exclude.list (docker/podman/snap)', SOURCES.stock, readFragment(SOURCES.stock)],
		['old exclude.list template items the built-ins do not cover (WO-870 1.3)', SOURCES.oldTemplate, readFragment(SOURCES.oldTemplate)],
		['old nest remnants under /home/eggs (WO-870 F8)', 'generate-eggs-config.js', ['home/eggs']],
		['HighAsCG ISO excludes incl. home/casparcg/highascg/media/* (the space check subtracts it)', server, readFragment(server)],
		['DeckLink / Blackmagic (WO-92)', SOURCES.decklink, readFragment(SOURCES.decklink)],
	]
	const all = withTwinsAndDedupe(parts.flatMap((p) => p[2]))
	// Attribute each line to the first part that produced it (or its twin) for the section comments.
	const lines = [
		'# /etc/penguins-eggs.d/custom.exclude.list',
		'# GENERATED by tools/eggs/live-usb/generate-eggs-config.js (install-eggs-config.sh) — DO NOT EDIT.',
		'# Edit the source fragments in tools/eggs/live-usb/ and re-apply; package upgrades overwrite this file.',
		'# Sources (in order): ' + [...new Set(parts.map((p) => p[1]))].filter((f) => f.endsWith('.list')).join(', '),
		'# Liveroot-relative paths, one pattern per line; every lib/ bin/ sbin/ lib64/ line has a usr/ twin (WO-430).',
	]
	const emitted = new Set()
	for (const [title, file, own] of parts) {
		const mine = []
		for (const l of own) {
			for (const cand of [l, MERGED_USR_RE.test(l) ? `usr/${l}` : null]) {
				if (cand && !emitted.has(cand)) {
					emitted.add(cand)
					mine.push(cand)
				}
			}
		}
		if (!mine.length) continue
		lines.push('', `# --- ${title} [${file}] ---`, ...mine)
	}
	if (emitted.size !== all.length) throw new Error('internal: section/line mismatch')
	return lines.join('\n') + '\n'
}

function buildCustomYaml({ branch }) {
	if (!/^[0-9]{3,}$/.test(String(branch || ''))) {
		throw new Error(`NVIDIA branch must be digits (e.g. 615), got "${branch || ''}"`)
	}
	return [
		'# /etc/penguins-eggs.d/custom.yaml',
		'# GENERATED by tools/eggs/live-usb/generate-eggs-config.js (install-eggs-config.sh) — DO NOT EDIT.',
		'# Package upgrades overwrite this file; the build re-applies it from the repo (WO-870 Phase 2).',
		'',
		'# Census opt-out (shop machine): replaces --anonymous.',
		'anonymous: true',
		'',
		'remaster:',
		'  # Replaces --basename: ISO is named <iso_prefix>-<YYYY-MM-DD_HHMM>.iso',
		`  iso_prefix: highascg-nvidia-${branch}`,
		'  # Replaces --max: xz always uses its strongest settings (1M blocks/dict, x86 BCJ) and ignores "level".',
		'  compression:',
		'    algorithm: "xz"',
		'    # level is zstd-only (kept from the stock file); xz ignores it',
		'    level: 3',
		'  # user/password stay at the defaults (unused in --clone).',
		'  # installer: calamares   # only after the launcher route is proven (makes remaster fatal without calamares)',
		'',
	].join('\n')
}

function main(argv) {
	const [cmd, ...rest] = argv
	const opt = (name) => {
		const i = rest.indexOf(name)
		return i >= 0 ? rest[i + 1] : undefined
	}
	if (cmd === 'exclude') {
		const embed = opt('--embed') ?? process.env.HIGHASCG_ISO_EMBED_SERVER ?? '1'
		process.stdout.write(buildExcludeList({ embedServer: embed !== '0' }))
	} else if (cmd === 'yaml') {
		process.stdout.write(buildCustomYaml({ branch: opt('--branch') }))
	} else {
		process.stderr.write('usage: generate-eggs-config.js exclude [--embed 0|1] | yaml --branch NNN\n')
		return 2
	}
	return 0
}

if (require.main === module) {
	try {
		process.exitCode = main(process.argv.slice(2))
	} catch (e) {
		process.stderr.write(`generate-eggs-config: ${e.message}\n`)
		process.exitCode = 1
	}
}

module.exports = { buildExcludeList, buildCustomYaml, cleanLine, MERGED_USR_RE }
